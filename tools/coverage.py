"""Regression coverage table and smoke-set choice.

Reads build/scan/scan.json (tools/scan_titles.py) and tests/titles.csv, derives
each title's features, writes Docs/coverage.md and the 'smoke' and 'features'
columns of tests/titles.csv. Smoke set = canaries (titles that broke before)
plus a greedy cover of every feature the canaries don't cover yet.
Usage: python tools/coverage.py"""
import csv, json, os

BASE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CMDS = {"F": "HMMC", "E": "YMMM", "D": "HMMM", "C": "HMMV", "B": "LMMC", "A": "LMCM",
        "9": "LMMM", "8": "LMMV", "7": "LINE", "6": "SRCH", "5": "PSET", "4": "POINT"}
SPLIT = {"0": "mode", "1": "mode", "2": "tables", "3": "tables", "4": "tables", "10": "tables",
         "5": "sprite-tables", "6": "sprite-tables", "11": "sprite-tables",
         "23": "scroll", "18": "adjust", "8": "sprites-on/off", "7": "border",
         "25": "MSX2+", "26": "MSX2+", "27": "MSX2+"}
# Titles that broke before (and what they guard).
CANARIES = {
    "M_Barbarian_A16": "SCREEN 5 sprite tables > 64 KB (D1 high word), odd ROM size",
    "007_UridiumMSXdev14": "5th-sprite flag, HUD sprite split, two cache banks, speed",
    "M_Lilly_A16": "SCREEN 4 table split + sprite bands, LMMM transparency",
    "R2_BunGaRua": "SCREEN 5/4 mode split, mid-frame palette, LMMC (R#4)",
    "R2_MonsterHunter[KonamiSCC]": "file-name mapper tag, KonamiSCC decode",
    "034_GodzillaBalls": "stack reads from ROM",
    "100_ChikubiNinja": "R#18 scrolling, mode-1 sprite snapshots",
    "R2_Popolon": "CPU-bound benchmark (Z80 core speed)",
    "R2_io": "timing self-check (M1 waits, 50 Hz, line length)",
}


def features(s, romtype, size):
    f = set()
    tot = max(1, s.get("frames", 1))
    modes = [m for m, n in s.get("modes", {}).items() if n * 50 >= tot]   # >= 2% of frames
    f |= {"mode:" + m for m in modes}
    msx2 = any(m in ("S4", "S5", "S6", "S7", "S8", "S0w80") for m in modes)
    if s.get("ie1"):
        f.add("line-interrupts"); msx2 = True
    for r in s.get("midregs", {}):
        k = SPLIT.get(r)
        if k:
            f.add("split:" + k)
            if k not in ("tables", "sprite-tables", "border"):
                msx2 = msx2 or k in ("mode", "scroll", "adjust", "MSX2+")
    for c in s.get("cmds", {}):
        if c in CMDS:
            f.add("cmd:" + CMDS[c]); msx2 = True
    if s.get("palmid", 0) > 0:
        f.add("palette:mid-frame"); msx2 = True
    elif s.get("palvbl", 0) > 0:
        f.add("palette")
    for r in ("23", "18"):
        if r in s.get("vblregs", {}):
            f.add("scroll:R#23" if r == "23" else "adjust:R#18"); msx2 = True
    if s.get("sprframes", 0) * 10 >= tot:
        f.add("sprites:mode2" if any(m in ("S4", "S5", "S6", "S7", "S8") for m in modes) else "sprites:mode1")
    f.add("machine:MSX2" if msx2 else "machine:MSX1")
    f.add("mapper:" + (romtype or ("plain" if size <= 65536 else "guess")))
    return f


def main():
    rows = list(csv.DictReader(open(os.path.join(BASE, "tests", "titles.csv"), encoding="utf-8")))
    scan = json.load(open(os.path.join(BASE, "build", "scan", "scan.json")))
    feats = {}
    for r in rows:
        path = os.path.join(BASE, "run", "Roms" if r["kind"] == "rom" else "Disks", r["file"])
        size = os.path.getsize(path) if os.path.exists(path) else 0
        if r["id"] in scan:
            feats[r["id"]] = features(scan[r["id"]], r["romtype"], size)
        elif r["kind"] == "disk":
            feats[r["id"]] = {"disk", "machine:MSX1"}
    usable = [r["id"] for r in rows if r["id"] in feats and "out of scope" not in r["notes"]]
    allf = set().union(*(feats[i] for i in usable))
    smoke = [c for c in CANARIES if c in feats]
    covered = set().union(*(feats[i] for i in smoke)) if smoke else set()
    while covered != allf:
        best = max(usable, key=lambda i: (len(feats[i] - covered), i in smoke))
        gain = feats[best] - covered
        if not gain:
            break
        smoke.append(best); covered |= gain
    for r in rows:
        r["smoke"] = "Y" if r["id"] in smoke else ""
        r["features"] = " ".join(sorted(feats.get(r["id"], [])))
    fields = list(rows[0].keys())
    with open(os.path.join(BASE, "tests", "titles.csv"), "w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=fields); w.writeheader(); w.writerows(rows)
    # Coverage table: features x titles (counts), and the smoke set.
    order = sorted(allf)
    lines = ["# Regression coverage", "",
             "Generated by `tools/coverage.py` from an openMSX scan of each title run with its key script "
             "(`tools/scan_titles.py`, 60 s, C-BIOS MSX2). Disk titles aren't scanned, because C-BIOS has no disk ROM.", "",
             f"**Smoke set ({len(smoke)} titles)**: the canaries plus a greedy cover of every feature:", ""]
    for i in smoke:
        why = CANARIES.get(i, "covers: " + ", ".join(sorted(feats[i] - set().union(*(feats[j] for j in smoke if j != i)))) or "covers: (shared)")
        lines.append(f"- `{i}`: {why}")
    lines += ["", "## Titles per feature", "", "| Feature | Titles | In the smoke set |", "|---|---|---|"]
    for f in order:
        ts = [i for i in usable if f in feats[i]]
        lines.append(f"| {f} | {len(ts)} | {', '.join(t for t in ts if t in smoke) or '-'} |")
    lines += ["", "## Features per title", "", "| Title | Smoke | Features |", "|---|---|---|"]
    for r in rows:
        if r["id"] in feats:
            lines.append(f"| {r['id']} | {'Y' if r['id'] in smoke else ''} | {' '.join(sorted(feats[r['id']]))} |")
    open(os.path.join(BASE, "Docs", "coverage.md"), "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print(f"{len(usable)} titles, {len(allf)} features, smoke set {len(smoke)}: {', '.join(smoke)}")


if __name__ == "__main__":
    main()
